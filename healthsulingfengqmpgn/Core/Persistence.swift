// MARK: - Persistence controller

final class PersistenceController {
    static let shared = PersistenceController()

    let container: NSPersistentContainer

    var context: NSManagedObjectContext { container.viewContext }

    init(inMemory: Bool = false) {
        let model = PersistenceController.makeModel()
        container = NSPersistentContainer(name: "HealthSense", managedObjectModel: model)

        if inMemory || ProcessInfo.processInfo.arguments.contains("-DSHInMemoryStore") {
            let description = NSPersistentStoreDescription()
            description.type = NSInMemoryStoreType
            container.persistentStoreDescriptions = [description]
        }

        container.loadPersistentStores { _, error in
            if let error {
                assertionFailure("Core Data store failed to load: \(error)")
            }
        }
        container.viewContext.automaticallyMergesChangesFromParent = true
        container.viewContext.mergePolicy = NSMergeByPropertyObjectTrumpMergePolicy
    }

    // MARK: Schema

    private static func attribute(
        _ name: String,
        _ type: NSAttributeType,
        optional: Bool = false,
        defaultValue: Any? = nil
    ) -> NSAttributeDescription {
        let attribute = NSAttributeDescription()
        attribute.name = name
        attribute.attributeType = type
        attribute.isOptional = optional
        attribute.defaultValue = defaultValue
        return attribute
    }

    private static func entity(
        _ name: String,
        _ attributes: [NSAttributeDescription],
        relationships: [NSRelationshipDescription] = []
    ) -> NSEntityDescription {
        let entity = NSEntityDescription()
        entity.name = name
        entity.managedObjectClassName = "healthsulingfengqmpgn." + name
        entity.properties = attributes + relationships
        return entity
    }

    private static func makeModel() -> NSManagedObjectModel {
        let measurement = entity("HeartRateMeasurementMO", [
            attribute("pulse", .integer32AttributeType, defaultValue: 0),
            attribute("hrv", .doubleAttributeType, defaultValue: 0),
            attribute("sdnn", .doubleAttributeType, defaultValue: 0),
            attribute("rmssd", .doubleAttributeType, defaultValue: 0),
            attribute("pnn50", .doubleAttributeType, defaultValue: 0),
            attribute("stress", .integer32AttributeType, defaultValue: 0),
            attribute("healthIndex", .doubleAttributeType, defaultValue: 0),
            attribute("csi", .integer32AttributeType, defaultValue: 0),
            attribute("energy", .integer32AttributeType, defaultValue: 0),
            attribute("source", .stringAttributeType, defaultValue: "inApp"),
            attribute("tagId", .stringAttributeType, optional: true),
            attribute("healthKitID", .stringAttributeType, optional: true),
            attribute("healthStateContextKey", .stringAttributeType, optional: true),
            attribute("generalHealthStateKey", .stringAttributeType, optional: true),
            attribute("hasReadAIComment", .booleanAttributeType, defaultValue: false),
            attribute("isTagAutoGenerated", .booleanAttributeType, defaultValue: false),
            attribute("createdAt", .dateAttributeType)
        ])

        let glucose = entity("GlucoseLogMO", [
            attribute("value", .doubleAttributeType, defaultValue: 0),
            attribute("tagId", .stringAttributeType, optional: true),
            attribute("createdAt", .dateAttributeType)
        ])
        let oxygen = entity("OxygenLogMO", [
            attribute("value", .integer32AttributeType, defaultValue: 0),
            attribute("tagId", .stringAttributeType, optional: true),
            attribute("createdAt", .dateAttributeType)
        ])
        let pressure = entity("PressureLogMO", [
            attribute("sys", .integer32AttributeType, defaultValue: 0),
            attribute("dia", .integer32AttributeType, defaultValue: 0),
            attribute("tagId", .stringAttributeType, optional: true),
            attribute("createdAt", .dateAttributeType)
        ])
        let reminder = entity("ReminderMO", [
            attribute("id", .UUIDAttributeType, defaultValue: UUID()),
            attribute("time", .dateAttributeType),
            attribute("type", .stringAttributeType, defaultValue: "pulse")
        ])
        let customTag = entity("CustomTagMO", [
            attribute("id", .UUIDAttributeType, defaultValue: UUID()),
            attribute("name", .stringAttributeType, defaultValue: ""),
            attribute("cluster", .stringAttributeType, defaultValue: "general"),
            attribute("colorName", .stringAttributeType, defaultValue: "green"),
            attribute("createdAt", .dateAttributeType)
        ])
        let synced = entity("SyncedHealthKitRecordMO", [
            attribute("healthKitID", .stringAttributeType, defaultValue: ""),
            attribute("recordType", .stringAttributeType, defaultValue: ""),
            attribute("syncedAt", .dateAttributeType)
        ])
        let achievement = entity("AchievementTierProgressMO", [
            attribute("achievementType", .stringAttributeType, defaultValue: ""),
            attribute("currentValue", .integer32AttributeType, defaultValue: 0),
            attribute("rewardValue", .integer32AttributeType, defaultValue: 0),
            attribute("completedAt", .dateAttributeType, optional: true),
            attribute("hasReceivedReward", .booleanAttributeType, defaultValue: false)
        ])

        let levelTasks = NSRelationshipDescription()
        levelTasks.name = "tasks"
        levelTasks.destinationEntity = nil // assigned after task entity creation
        levelTasks.minCount = 0
        levelTasks.maxCount = 0
        levelTasks.deleteRule = .cascadeDeleteRule
        levelTasks.isOptional = true

        let level = entity("JourneyLevelProgressMO", [
            attribute("levelId", .stringAttributeType, defaultValue: ""),
            attribute("startedAt", .dateAttributeType)
        ], relationships: [levelTasks])

        let taskLevel = NSRelationshipDescription()
        taskLevel.name = "level"
        taskLevel.destinationEntity = level
        taskLevel.minCount = 0
        taskLevel.maxCount = 1
        taskLevel.deleteRule = .nullifyDeleteRule
        taskLevel.isOptional = true

        let task = entity("JourneyTaskProgressMO", [
            attribute("taskId", .stringAttributeType, defaultValue: ""),
            attribute("currentValue", .integer32AttributeType, defaultValue: 0),
            attribute("targetValue", .integer32AttributeType, defaultValue: 0),
            attribute("category", .stringAttributeType, defaultValue: "any_measures_vol"),
            attribute("type", .stringAttributeType, defaultValue: "core"),
            attribute("referenceId", .stringAttributeType, optional: true),
            attribute("completedAt", .dateAttributeType, optional: true)
        ], relationships: [taskLevel])

        levelTasks.destinationEntity = task
        levelTasks.inverseRelationship = taskLevel
        taskLevel.inverseRelationship = levelTasks

        let model = NSManagedObjectModel()
        model.entities = [measurement, glucose, oxygen, pressure, reminder, customTag, synced, level, task, achievement]
        return model
    }

    // MARK: Helpers

    func save() {
        guard context.hasChanges else { return }
        do {
            try context.save()
        } catch {
            context.rollback()
            assertionFailure("Core Data save failed: \(error)")
        }
    }

    func count<T: NSManagedObject>(_ type: T.Type, predicate: NSPredicate? = nil) -> Int {
        let request = NSFetchRequest<T>(entityName: String(describing: type))
        request.predicate = predicate
        return (try? context.count(for: request)) ?? 0
    }

    func fetch<T: NSManagedObject>(
        _ type: T.Type,
        sortBy key: String? = nil,
        ascending: Bool = false,
        predicate: NSPredicate? = nil,
        limit: Int? = nil
    ) -> [T] {
        let request = NSFetchRequest<T>(entityName: String(describing: type))
        if let key {
            request.sortDescriptors = [NSSortDescriptor(key: key, ascending: ascending)]
        }
        request.predicate = predicate
        if let limit { request.fetchLimit = limit }
        return (try? context.fetch(request)) ?? []
    }
}

// MARK: - Domain helpers

extension HeartRateMeasurementMO {
    var sourceKind: MeasurementSource {
        MeasurementSource(rawValue: source) ?? .inApp
    }

    var tagInfo: TagInfo? {
        guard let tagId else { return nil }
        return TagCatalog.info(for: tagId)
    }
}

enum MeasurementSource: String {
    case inApp
    case appleWatch
}

